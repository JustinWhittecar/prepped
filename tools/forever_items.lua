-- Writes Prepped/data/ForeverItems.lua from a /prep harvest: the class-restricted items in
-- PreppedDB.harvest, raw as the game gave them. Run after a harvest and a /reload:
--   luajit tools/forever_items.lua <account SavedVariables/Prepped.lua>
local path = assert(arg[1], "usage: luajit tools/forever_items.lua <account SavedVariables/Prepped.lua>")
local env = {}
local chunk = assert(loadfile(path))
setfenv(chunk, env)()
local h = assert(env.PreppedDB and env.PreppedDB.harvest, "no harvest in " .. path)

local ids = {}
for id, r in pairs(h.records) do if r.classes and r.slot and r.slot ~= "" then ids[#ids + 1] = id end end
table.sort(ids)

local function q(s) return string.format("%q", s) end
local function sortedKeys(t) local k = {} for key in pairs(t) do k[#k + 1] = key end table.sort(k) return k end
local out = {
  "-- GENERATED by tools/forever_items.lua from a /prep harvest. Do not edit; harvest again and regenerate.",
  "-- Forever items SimGear can't see (sent by the server, not in the client's item table): name, slot,",
  "-- levels, quality, classes and GetItemStats' raw stats, as the game reported them.",
  ("-- Client %s, ranges %s, %d items."):format(tostring(h.build), table.concat(h.ranges or {}, ", "), #ids),
  "local _, ns = ...",
  "ns.ForeverItemData = {",
}
for _, id in ipairs(ids) do
  local r = h.records[id]
  local classes, raw = {}, {}
  for _, c in ipairs(sortedKeys(r.classes)) do classes[#classes + 1] = c .. " = true" end
  for _, k in ipairs(sortedKeys(r.raw)) do raw[#raw + 1] = k .. " = " .. tostring(r.raw[k]) end
  out[#out + 1] = ("  [%d] = { name = %s, slot = %q, quality = %d, ilvl = %d, req = %d, classes = { %s }, raw = { %s } },")
    :format(id, q(r.name), r.slot, r.quality or 0, r.ilvl or 0, r.req or 0, table.concat(classes, ", "), table.concat(raw, ", "))
end
out[#out + 1] = "}"
local f = assert(io.open("Prepped/data/ForeverItems.lua", "w"))
f:write(table.concat(out, "\n"), "\n")
f:close()
print(("wrote Prepped/data/ForeverItems.lua: %d items"):format(#ids))
