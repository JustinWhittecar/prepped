-- Builds Prepped's backup copy: per-class LoadOnDemand addons (PreppedBackup_<Class>/) holding the
-- level-60 part of a pinned SimGear Forever release, for Core to load when the live read fails.
--   luajit tools/build_backup.lua [SimGear AddOns dir] [--out dir] [--any-version]
-- Run from the repo root. The AddOns dir defaults to the installed game's; --out to the repo root.
-- SimGear's files run in a sandbox: they see only Lua's basic library and write only into it.
local L = dofile("tools/backup_lib.lua")

-- The SimGear release this copy is built from. Bump it on purpose, after checking the new release
-- in game; --any-version builds from whatever is installed (for a look, not to commit).
local PIN = "0.16.0"
local CLASSES = { "Druid", "Hunter", "Mage", "Paladin", "Priest", "Rogue", "Shaman", "Warlock", "Warrior" }

local dir, out, anyVersion
local i = 1
while arg[i] do
  if arg[i] == "--out" then out, i = arg[i + 1], i + 1
  elseif arg[i] == "--any-version" then anyVersion = true
  else dir = arg[i] end
  i = i + 1
end
dir = dir or (os.getenv("HOME") .. "/WoW/_forever_/Interface/AddOns")
out = out or "."

-- Prepped's own scoring, to rank candidates as the addon will (tools run Prepped's files as WoW does).
local ns = {}
for _, f in ipairs({ "SimGearShim.lua", "vendor/SimGear/Stats.lua", "vendor/SimGear/HitCap.lua", "vendor/SimGear/Score.lua", "SimGear.lua" }) do
  assert(loadfile("Prepped/" .. f))("Prepped", ns)
end

local function readToc(path)
  local f = assert(io.open(path), "not found: " .. path)
  local meta, files = {}, {}
  for line in f:lines() do
    local k, v = line:match("^##%s*([^:]+):%s*(.-)%s*$")
    if k then meta[k] = v
    elseif not line:match("^#") and line:match("%.lua%s*$") then files[#files + 1] = (line:gsub("\\", "/"):gsub("%s+$", "")) end
  end
  f:close()
  return meta, files
end

-- Only what data files need: no io, os, loadfile or the tool's own globals.
local SAFE = {}
for _, k in ipairs({ "pairs", "ipairs", "next", "type", "tostring", "tonumber", "select", "unpack", "error", "assert",
  "setmetatable", "getmetatable", "rawget", "rawset", "rawequal", "pcall" }) do SAFE[k] = _G[k] end
for _, k in ipairs({ "math", "string", "table" }) do
  SAFE[k] = {}
  for name, fn in pairs(_G[k]) do SAFE[k][name] = fn end
end

-- Runs one class addon's files in a fresh sandbox, as WoW would (addon name, shared namespace).
local function loadClass(cls)
  local name = "SimGearForever_" .. cls
  local meta, files = readToc(dir .. "/" .. name .. "/" .. name .. ".toc")
  local env = setmetatable({}, { __index = SAFE })
  local addonNS = {}
  for _, file in ipairs(files) do
    local chunk = assert(loadfile(dir .. "/" .. name .. "/" .. file))
    setfenv(chunk, env)(name, addonNS)
  end
  return rawget(env, "SimGearForeverData"), meta
end

local function count(t) local n = 0 for _ in pairs(t or {}) do n = n + 1 end return n end
local prepMeta = readToc("Prepped/Prepped.toc")
local built = os.date("%Y-%m-%d")

local function write(path, text)
  local f = assert(io.open(path, "w"))
  f:write(text)
  f:close()
  return #text
end

print(("SimGear Forever from %s, pinned %s, built %s"):format(dir, PIN, built))
local total = 0
for _, cls in ipairs(CLASSES) do
  local token = cls:upper()
  local global, meta = loadClass(cls)
  if meta.Version ~= PIN and not anyVersion then
    error(("%s is SimGear %s, pinned %s: check the new release in game, then bump PIN (or --any-version)"):format(cls, tostring(meta.Version), PIN))
  end
  -- The shape the addon checks, checked here too, so a reshaped release fails the build, not the game.
  local _, why = ns.SimGear.load(global, token)
  assert(not why, cls .. ": " .. tostring(why))
  local c = global[token]
  local im = c.items.meta or {}
  local stamp = { built = built, simgearVersion = meta.Version, itemsGenerated = im.generated, clientBuild = im.clientBuild,
    weightsGenerated = c.weights.meta and c.weights.meta.generated }
  local trimmed = L.trim(c, ns.Score, stamp)
  local name = "PreppedBackup_" .. cls
  os.execute(("mkdir -p '%s/%s'"):format(out, name))
  local header = table.concat({
    "-- GENERATED by tools/build_backup.lua. Do not edit; regenerate.",
    "-- SPDX-License-Identifier: GPL-3.0-or-later",
    ("-- A trimmed copy of SimGear Forever %s's %s data (GPL-3.0-or-later; items generated %s, client %s, weights"):format(
      meta.Version, cls, tostring(im.generated), tostring(im.clientBuild)),
    ("--   generated %s), built %s: level-60 candidates (tools/backup_lib.lua), each spec's level-60 weight set and"):format(
      tostring(stamp.weightsGenerated), built),
    "--   the sims and extras Prepped reads. SimGear's sources: cMaNGOS classic-db (GPL-3.0) and the Forever client.",
    "--   World of Warcraft content is (c) Blizzard Entertainment.",
    "-- Prepped loads this only when SimGear Forever's own data is missing or reshaped (Backup.lua).",
  }, "\n")
  local data = header .. "\nPreppedBackupData = PreppedBackupData or {}\nPreppedBackupData." .. token .. " = "
    .. L.serialize(trimmed, 3) .. "\n"
  local size = write(out .. "/" .. name .. "/Data.lua", data)
  write(out .. "/" .. name .. "/" .. name .. ".toc", table.concat({
    "## Interface: " .. prepMeta.Interface,
    "## Title: Prepped Backup - " .. cls,
    ("## Notes: Prepped's snapshot of SimGear Forever's %s data, loaded only when SimGear's own can't be read. Leave it enabled."):format(cls),
    "## Author: " .. prepMeta.Author,
    "## Version: " .. meta.Version .. "-" .. built,
    "## LoadOnDemand: 1",
    "",
    "Data.lua",
    "",
  }, "\n"))
  -- Read back what was written, as the addon will, so a bad write fails here.
  local env = setmetatable({}, { __index = SAFE })
  setfenv(assert(loadfile(out .. "/" .. name .. "/Data.lua")), env)(name, {})
  local back, backWhy = ns.SimGear.load(rawget(env, "PreppedBackupData"), token)
  assert(back, name .. " doesn't read back: " .. tostring(backWhy))
  total = total + size
  print(("  %-8s %5d of %5d items, %2d specs, %7.0f KB  %s/Data.lua"):format(cls, count(back.items), count(c.items.items),
    count(back.specs), size / 1024, name))
end
-- The sandbox held: nothing SimGear or the backup defines reached the tool's globals.
assert(rawget(_G, "SimGearForeverData") == nil and rawget(_G, "PreppedBackupData") == nil, "a data file wrote a global")
print(("total %.1f MB"):format(total / 1048576))
