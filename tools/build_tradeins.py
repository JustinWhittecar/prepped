"""Builds Prepped/data/TradeIns.lua: what each class hands in for its tier 0.5 pieces.

Forever's tier 0.5 pieces (Deliana in Ironforge, Mokvar in Orgrimmar) are new item IDs, but the quests
that give them are classic's, with the same names, IDs and hand-ins (checked against Wowhead's Forever
quest tooltips, 2026-11-25). So the hand-ins come from cMaNGOS classic-db (GPL), the same pinned dump
build_lists.py reads: for the four upgrade quests, each class's and side's quest ID, who it is turned in to, the
items and gold it takes, and the equip slots of what it gives. Prepped matches a Forever piece to its
quest by class and slot, since every variant of a slot comes from the same quest.

Usage (repo root): python3 -I tools/build_tradeins.py <ClassicDB .sql.gz>
"""
import gzip, importlib.util, os, sys

spec = importlib.util.spec_from_file_location("build_lists", os.path.join(os.path.dirname(os.path.abspath(__file__)), "build_lists.py"))
bl = importlib.util.module_from_spec(spec)
spec.loader.exec_module(bl)

QUESTS = ["An Earnest Proposition", "Just Compensation", "Anthion's Parting Words", "Saving the Best for Last"]
CLASSES = {1: "WARRIOR", 2: "PALADIN", 4: "HUNTER", 8: "ROGUE", 16: "PRIEST", 64: "SHAMAN", 128: "MAGE", 256: "WARLOCK", 1024: "DRUID"}
SIDES = {77: "Alliance", 178: "Horde"}
SLOTS = {1: "INVTYPE_HEAD", 3: "INVTYPE_SHOULDER", 5: "INVTYPE_CHEST", 6: "INVTYPE_WAIST", 7: "INVTYPE_LEGS",
         8: "INVTYPE_FEET", 9: "INVTYPE_WRIST", 10: "INVTYPE_HAND", 20: "INVTYPE_CHEST"}
OUT = "Prepped/data/TradeIns.lua"

def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

def main(dump):
    with gzip.open(dump, "rt", encoding="utf-8", errors="replace") as f:
        lines = f.read().split("\n")
    ic, items = bl.rows(lines, "item_template")
    names = {int(r[ic["entry"]]): r[ic["name"]] for r in items}
    slot = {int(r[ic["entry"]]): int(r[ic["InventoryType"]]) for r in items}
    cc, creatures = bl.rows(lines, "creature_template")
    npc = {int(r[cc["Entry"]]): r[cc["Name"]] for r in creatures}
    rc, rels = bl.rows(lines, "creature_involvedrelation")
    turn_in = {}
    for r in rels: turn_in.setdefault(int(r[rc["quest"]]), npc.get(int(r[rc["id"]])))
    qc, quests = bl.rows(lines, "quest_template")
    titles = {int(r[qc["entry"]]): r[qc["Title"]] for r in quests}
    out = {}
    for r in quests:
        title = r[qc["Title"]]
        token, side = CLASSES.get(int(r[qc["RequiredClasses"]])), SIDES.get(int(r[qc["RequiredRaces"]]))
        if title not in QUESTS or not token or not side: continue
        qid = int(r[qc["entry"]])
        needs = [(int(r[qc["ReqItemId%d" % k]]), int(r[qc["ReqItemCount%d" % k]])) for k in range(1, 5)]
        needs = [(i, n) for i, n in needs if i > 0]
        gives = [int(r[qc[c]]) for c in ["RewChoiceItemId%d" % k for k in range(1, 7)] + ["RewItemId%d" % k for k in range(1, 5)]]
        slots = sorted({SLOTS[slot[i]] for i in gives if i > 0 and slot.get(i) in SLOTS})
        assert needs and slots, (qid, title)
        money = max(0, -int(r[qc["RewOrReqMoney"]]))
        prev = abs(int(r[qc["PrevQuestId"]]))  # negative: must be in the log, positive: done; either way it comes first
        out.setdefault(token, []).append((QUESTS.index(title), side, qid, title, turn_in.get(qid) or "?", slots, money, needs, prev))
    # Every class has all four on its side(s): a missing one means the dump or the titles changed.
    for token in CLASSES.values():
        got = {(q[0], q[1]) for q in out.get(token, [])}
        sides = {q[1] for q in out.get(token, [])}
        assert sides and all((k, s) in got for k in range(4) for s in sides), (token, sorted(got))
    w = ["-- GENERATED by tools/build_tradeins.py from cMaNGOS classic-db %s. Do not edit; regenerate." % bl.COMMIT,
         "-- Tier 0.5 hand-ins: per class, each upgrade quest on each side, who takes it in, the gold and items it",
         "-- takes, the equip slots of the pieces it gives and the quest it follows (after). Forever's quests",
         "-- match (Wowhead, 2026-11-25).",
         "local _, ns = ...", "ns.TradeInData = {"]
    for token in sorted(out):
        w.append("  %s = {" % token)
        for _, side, qid, title, who, slots, money, needs, prev in sorted(out[token]):
            n = ", ".join("{ id = %d, n = %d, name = %s }" % (i, c, lua_str(names.get(i, "item %d" % i))) for i, c in needs)
            after = (", after = { id = %d, quest = %s }" % (prev, lua_str(titles[prev]))) if prev else ""
            w.append("    { quest = %s, id = %d, faction = %s, turnIn = %s, money = %d, slots = { %s }, needs = { %s }%s }," % (
                lua_str(title), qid, lua_str(side), lua_str(who), money, ", ".join(lua_str(s) for s in slots), n, after))
        w.append("  },")
    w.append("}")
    with open(OUT, "w") as f: f.write("\n".join(w) + "\n")
    print("%s: %d classes, %d quests" % (OUT, len(out), sum(len(v) for v in out.values())))

if __name__ == "__main__":
    main(sys.argv[1])
